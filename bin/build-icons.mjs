#!/usr/bin/env node
/**
 * Builds assets/vendor/phosphor/phosphor.css: a subset of @phosphor-icons/web with only the
 * icons used in templates/, src/ and assets/js/, plus the woff2 fonts of the weights in use.
 *
 *   node bin/build-icons.mjs <path-to-@phosphor-icons/web/src>
 *
 * Get the package with `npm pack @phosphor-icons/web@2.1.2` and extract it.
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) {
    console.error('usage: node bin/build-icons.mjs <phosphor-web/src>');
    process.exit(1);
}

const WEIGHTS = {
    regular: { cls: 'ph', font: 'Phosphor' },
    fill: { cls: 'ph-fill', font: 'Phosphor-Fill' },
    duotone: { cls: 'ph-duotone', font: 'Phosphor-Duotone' },
    bold: { cls: 'ph-bold', font: 'Phosphor-Bold' },
};

function walk(dir) {
    return readdirSync(dir).flatMap((name) => {
        const path = join(dir, name);
        return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

// Collect "<weight-class> ph-<icon>" usages. `ph ph-copy` is also written by admin.js at runtime.
const used = Object.fromEntries(Object.keys(WEIGHTS).map((w) => [w, new Set()]));
const sources = [...walk(join(root, 'templates')), ...walk(join(root, 'src')), ...walk(join(root, 'assets/js'))].filter((f) => ['.php', '.js'].includes(extname(f)));
const usage = /\b(ph|ph-fill|ph-duotone|ph-bold)\s+(?:[a-z-]+\s+)?ph-([a-z0-9-]+)/g;
for (const file of sources) {
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(usage)) {
        const weight = Object.keys(WEIGHTS).find((w) => WEIGHTS[w].cls === m[1]);
        used[weight].add(m[2]);
    }
    // Icon names passed separately from the weight class (e.g. 'icon' => 'ph-device-mobile').
    for (const m of text.matchAll(/'(ph-[a-z0-9-]+)'/g)) {
        const name = m[1].slice(3);
        if (!['fill', 'duotone', 'bold'].includes(name)) used.regular.add(name);
    }
}
// Runtime-only icons (copy feedback in admin.js / order-status.js, badges and notes chosen in PHP).
['check', 'copy'].forEach((n) => used.regular.add(n));
['check-circle', 'warning-circle', 'warning', 'shield-check', 'arrow-u-up-left', 'clock'].forEach((n) => used.fill.add(n));

const out = join(root, 'assets/vendor/phosphor');
mkdirSync(out, { recursive: true });

let css = '/* Phosphor Icons 2.1.2 (MIT), subset for Carbon Pay. Generated by bin/build-icons.mjs. */\n';
for (const [weight, { cls, font }] of Object.entries(WEIGHTS)) {
    if (used[weight].size === 0) continue;
    const sheet = readFileSync(join(src, weight, 'style.css'), 'utf8');
    copyFileSync(join(src, weight, `${font}.woff2`), join(out, `${font}.woff2`));

    css += `@font-face{font-family:"${font}";src:url("./${font}.woff2") format("woff2");font-weight:normal;font-style:normal;font-display:block}\n`;

    for (const block of sheet.split('}')) {
        const [selector, body] = block.split('{').map((s) => (s || '').trim());
        if (!selector || !body || selector.startsWith('@font-face')) continue;
        const icon = selector.match(/\.ph(?:-fill|-duotone|-bold)?\.ph-([a-z0-9-]+)/);
        if (!icon || used[weight].has(icon[1])) {
            css += `${selector}{${body.replace(/\s*\n\s*/g, '')}}\n`;
        }
    }
}

writeFileSync(join(out, 'phosphor.css'), css);
for (const [weight, names] of Object.entries(used)) {
    console.log(`${weight}: ${[...names].sort().join(' ')}`);
}
